// Original code, not ported from d3-chord: Node.js reference vector generator.

import {writeFileSync} from "node:fs";
import {registerHooks} from "node:module";
import path from "node:path";
import {fileURLToPath, pathToFileURL} from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = path.resolve(here, "../..");
const repo = path.resolve(pkg, "../..");

const d3PathUrl = pathToFileURL(
  path.join(repo, "third_party/d3-path/src/index.js"),
).href;

registerHooks({
  resolve(specifier, context, nextResolve) {
    if (specifier === "d3-path") {
      return {shortCircuit: true, url: d3PathUrl};
    }
    return nextResolve(specifier, context);
  },
});

const d3 = await import(
  pathToFileURL(path.join(repo, "third_party/d3-chord/src/index.js")).href
);

// 1. Circos 4x4 matrix
const circos = [
  [11975, 5871, 8916, 2868],
  [1951, 10048, 2060, 6171],
  [8010, 16145, 8090, 8045],
  [1013, 990, 940, 6907],
];

// 2. Asymmetric sparse 6x6 directed network with zeros & self-loops
const sparse6 = [
  [0, 120, 0, 45, 0, 30],
  [80, 15, 210, 0, 60, 0],
  [0, 0, 0, 190, 110, 25],
  [55, 0, 95, 40, 0, 140],
  [20, 75, 0, 0, 0, 85],
  [0, 35, 65, 0, 50, 10],
];

const asc = (a, b) => a - b;
const desc = (a, b) => b - a;

const cases = [
  {
    name: "undirectedDefault",
    matrix: circos,
    chords: d3.chord()(circos),
    ribbons: d3.chord()(circos).map((c) => d3.ribbon().radius(240)(c)),
  },
  {
    name: "undirectedSortedPadded",
    matrix: circos,
    chords: d3.chord().padAngle(0.06).sortGroups(desc).sortSubgroups(desc).sortChords(desc)(circos),
    ribbons: d3
      .chord()
      .padAngle(0.06)
      .sortGroups(desc)
      .sortSubgroups(desc)
      .sortChords(desc)(circos)
      .map((c) => d3.ribbon().sourceRadius(220).targetRadius(200).padAngle(0.01)(c)),
  },
  {
    name: "directedSparse6",
    matrix: sparse6,
    chords: d3.chordDirected().padAngle(0.04).sortGroups(asc).sortSubgroups(desc).sortChords(asc)(sparse6),
    ribbons: d3
      .chordDirected()
      .padAngle(0.04)
      .sortGroups(asc)
      .sortSubgroups(desc)
      .sortChords(asc)(sparse6)
      .map((c) => d3.ribbonArrow().sourceRadius(180).targetRadius(170).headRadius(12).padAngle(0.005)(c)),
  },
  {
    name: "transposeSparse6",
    matrix: sparse6,
    chords: d3.chordTranspose().padAngle(0.05).sortSubgroups(asc)(sparse6),
    ribbons: d3
      .chordTranspose()
      .padAngle(0.05)
      .sortSubgroups(asc)(sparse6)
      .map((c) => d3.ribbon().radius(150)(c)),
  },
];

function fmtSub(s) {
  return `ChordSubgroup(index: ${s.index}, startAngle: ${s.startAngle}, endAngle: ${s.endAngle}, value: ${s.value})`;
}

function fmtGroup(g) {
  return `ChordGroup(index: ${g.index}, startAngle: ${g.startAngle}, endAngle: ${g.endAngle}, value: ${g.value})`;
}

const lines = [
  "// Original code, not ported from d3-chord: Node.js v3.0.1 reference vectors.",
  "// Generated by tool/reference/generate_reference.mjs.",
  "// ignore_for_file: lines_longer_than_80_chars",
  "",
  "import 'package:flutter_d3_chord_port/d3_chord.dart';",
  "",
  "/// One Node.js v3.0.1 reference parity vector.",
  "final class const RefChordCase({",
  "  /// Case name.",
  "  required final String name,",
  "  /// Expected outer groups.",
  "  required final List<ChordGroup> groups,",
  "  /// Expected chords.",
  "  required final List<Chord> chords,",
  "  /// Expected SVG ribbon path strings.",
  "  required final List<String> ribbons,",
  "}) {",
  "  /// Creates a reference case.",
  "  this;",
  "}",
  "",
  "/// Circos 4x4 flow matrix.",
  "const List<List<double>> refCircosMatrix = <List<double>>[",
  ...circos.map((row) => `  <double>[${row.join(", ")}],`),
  "];",
  "",
  "/// Sparse asymmetric 6x6 directed flow matrix.",
  "const List<List<double>> refSparse6Matrix = <List<double>>[",
  ...sparse6.map((row) => `  <double>[${row.join(", ")}],`),
  "];",
  "",
];

for (const c of cases) {
  const cap = c.name[0].toUpperCase() + c.name.slice(1);
  lines.push(`/// Node.js v3.0.1 reference vector for ${c.name}.`);
  lines.push(`const RefChordCase ref${cap} = RefChordCase(`);
  lines.push(`  name: '${c.name}',`);
  lines.push(`  groups: <ChordGroup>[`);
  for (const g of c.chords.groups) {
    lines.push(`    ${fmtGroup(g)},`);
  }
  lines.push(`  ],`);
  lines.push(`  chords: <Chord>[`);
  for (const ch of c.chords) {
    lines.push(`    Chord(`);
    lines.push(`      source: ${fmtSub(ch.source)},`);
    lines.push(`      target: ${fmtSub(ch.target)},`);
    lines.push(`    ),`);
  }
  lines.push(`  ],`);
  lines.push(`  ribbons: <String>[`);
  for (const r of c.ribbons) {
    lines.push(`    '${r}',`);
  }
  lines.push(`  ],`);
  lines.push(`);`);
  lines.push("");
}

writeFileSync(
  path.join(pkg, "test/port/d3_chord_reference.dart"),
  lines.join("\n"),
);
console.log("Wrote test/port/d3_chord_reference.dart");
