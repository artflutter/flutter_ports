// Original code, not ported from Chart.js: V8 Math.atan2 reference generator.
//
// It writes test/port/js/atan2_reference.dart, the data of
// test/port/js/fdlibm_atan_test.dart: 3,000 (y, x) inputs, each with the bits
// of Math.atan2(y, x), and the Node.js version, V8 version and architecture in
// the header. The inputs are deterministic, so a rerun on the same Node.js
// writes the same file. Nothing in lib/ or test/ runs this script
// (porting-flow.md section 4).
//
// Usage, from packages/flutter_chartjs, with an x64 build of Node.js v24.12.0
// (on Apple silicon, the darwin-x64 build runs under Rosetta):
//
//   node tool/reference/atan2_reference.mjs
//
// The reference is V8 13.6 on x64 (porting-flow.md 2.3), and the script stops
// on any other architecture. V8 on arm64 compiles fdlibm with fused
// multiply-add and differs in the last bit for some inputs.

import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

if (process.arch !== 'x64') {
  console.error(
    `The reference is V8 on x64; this Node.js is ${process.arch}. ` +
      'Run an x64 build of Node.js.',
  );
  process.exit(1);
}

const TOTAL = 3000;
const OUT = fileURLToPath(
  new URL('../../test/port/js/atan2_reference.dart', import.meta.url),
);

const view = new DataView(new ArrayBuffer(8));

/** The double whose IEEE-754 words are `hi` and `lo`. */
function fromWords(hi, lo) {
  view.setUint32(0, hi >>> 0);
  view.setUint32(4, lo >>> 0);
  return view.getFloat64(0);
}

/** The 16 hex digits of the bits of `x`. */
function hex(x) {
  view.setFloat64(0, x);
  return (
    view.getUint32(0).toString(16).padStart(8, '0') +
    view.getUint32(4).toString(16).padStart(8, '0')
  );
}

/** The double `steps` units in the last place away from finite `x` > 0. */
function ulpStep(x, steps) {
  view.setFloat64(0, x);
  view.setBigUint64(0, view.getBigUint64(0) + BigInt(steps));
  return view.getFloat64(0);
}

/** Marsaglia's xorshift32, from a fixed seed. */
let state = 0x6a09e667;
function next32() {
  state ^= state << 13;
  state ^= state >>> 17;
  state ^= state << 5;
  return state >>> 0;
}

/** A random double with the biased exponent `e` and a random sign. */
function random(e) {
  return fromWords(
    ((next32() & 1) << 31) | (e << 20) | (next32() & 0xfffff),
    next32(),
  );
}

const inputs = [];
const seen = new Set();
function add(y, x) {
  const key = `${hex(y)} ${hex(x)}`;
  if (seen.has(key) || inputs.length >= TOTAL) return;
  seen.add(key);
  inputs.push([y, x]);
}

// Every pair of special values: the special cases of e_atan2.c.
const special = [
  0, -0, Infinity, -Infinity, NaN, 1, -1, 2, -2, 0.5, Number.MIN_VALUE,
  -Number.MIN_VALUE, 1e300, -1e300, 1e-300, -1e-300, Number.MAX_VALUE,
  -Number.MAX_VALUE, 2 ** -1022, Math.PI,
];
for (const y of special) for (const x of special) add(y, x);

// Inputs where dart:math atan2 or netlib fdlibm 5.3 differ from V8.
// getAngleFromPoint adds TAU when the angle is below -PI/2, so a last-bit
// difference near -PI/2 changes its result by 2*PI.
add(-1e17, -1); // V8 -1.5707963267948968, macOS libm -1.5707963267948966
add(-5e-324, 502.77); // V8 -0, Chrome 155 +0
add(1e300, -1e-300); // |y/x| > 2**60 and x < 0: V8 pi/2, netlib pi/2 + 1 ulp
add(-1e300, -1e-300);
add(-1000, -5.551115123125783e-17); // 0.3 - (0.1 + 0.2) as x

// |y/x| on both sides of 2**60 and 2**-60, for every sign of y and x.
for (let k = 58; k <= 63; k++) {
  for (const s of [-k, k]) {
    for (let n = 0; n < 3; n++) {
      const e = 400 + (next32() % 1200);
      add(random(e + s), random(e));
    }
  }
}

// x = 1, which calls atan(y) directly, with y at the interval bounds of
// s_atan.c (and at 2**-27, the bound of the V8 and FreeBSD atan).
for (const t of [7 / 16, 11 / 16, 19 / 16, 39 / 16, 2 ** 66, 2 ** -29, 2 ** -27]) {
  for (const steps of [-2, -1, 0, 1, 2]) {
    add(ulpStep(t, steps), 1);
    add(-ulpStep(t, steps), 1);
  }
}

// Random doubles over the whole range.
for (let n = 0; n < 500; n++) add(random(next32() % 2047), random(next32() % 2047));

// Random doubles with exponents within 70 of each other: every path of atan.
while (inputs.length < TOTAL) {
  const e = 1 + (next32() % 2045);
  const d = (next32() % 141) - 70;
  add(random(e), random(Math.min(2046, Math.max(1, e + d))));
}

const lines = inputs.map(([y, x]) => `${hex(y)} ${hex(x)} ${hex(Math.atan2(y, x))}`);

const dart = `// Original code, not ported from Chart.js: V8 Math.atan2 reference data.

// Generated by tool/reference/atan2_reference.mjs. Do not edit.
// Node.js ${process.version} (${process.platform}-${process.arch}), V8 ${process.versions.v8}:
// fdlibm 5.3 without fused multiply-add. ${lines.length} inputs.

/// The Node.js version that generated [atan2Reference].
const String atan2ReferenceNode = '${process.version}';

/// The V8 version that generated [atan2Reference].
const String atan2ReferenceV8 = '${process.versions.v8}';

/// The architecture of the Node.js build that generated [atan2Reference].
const String atan2ReferenceArch = '${process.arch}';

/// \`y\`, \`x\` and V8 \`Math.atan2(y, x)\` as IEEE-754 bit patterns in hex, one
/// triple per line.
const String atan2Reference = '''
${lines.join('\n')}
''';
`;

writeFileSync(OUT, dart);
console.log(`Wrote ${lines.length} inputs to ${OUT}`);
