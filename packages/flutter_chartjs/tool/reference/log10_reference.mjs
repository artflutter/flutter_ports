// Original code, not ported from Chart.js: V8 Math.log10 reference generator.
//
// It writes test/port/js/log10_reference.dart, the data of
// test/port/js/fdlibm_log_test.dart: 5,909 inputs, then the regression inputs
// below, each with the bits of Math.log10, and the Node.js version, V8 version
// and architecture in the header. The inputs are deterministic, so a rerun on
// the same Node.js writes the same file. Nothing in lib/ or test/ runs this
// script (porting-flow.md section 4).
//
// Usage, from packages/flutter_chartjs, with an x64 build of Node.js v24.12.0
// (on Apple silicon, the darwin-x64 build runs under Rosetta):
//
//   node tool/reference/log10_reference.mjs
//
// The reference is V8 13.6 on x64 (Chart.js ADR 0010), and the script stops
// on any other architecture. V8 compiles fdlibm without fused multiply-add on
// x64 and with it on arm64, so the two builds differ in the last bit for some
// inputs: netlib e_log10.c compiled by clang with -ffp-contract=off gives the
// x64 results, which the Dart port matches, and with -ffp-contract=on the
// arm64 results.

import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

if (process.arch !== 'x64') {
  console.error(
    `The reference is V8 on x64; this Node.js is ${process.arch}. ` +
      'Run an x64 build of Node.js.',
  );
  process.exit(1);
}

const TOTAL = 5909;
const OUT = fileURLToPath(
  new URL('../../test/port/js/log10_reference.dart', import.meta.url),
);

const view = new DataView(new ArrayBuffer(8));

/** The double whose IEEE-754 words are `hi` and `lo`. */
function fromWords(hi, lo) {
  view.setUint32(0, hi >>> 0);
  view.setUint32(4, lo >>> 0);
  return view.getFloat64(0);
}

/** The 16 hex digits of the bits of `x`. */
function hex(x) {
  view.setFloat64(0, x);
  return (
    view.getUint32(0).toString(16).padStart(8, '0') +
    view.getUint32(4).toString(16).padStart(8, '0')
  );
}

/** The double `steps` units in the last place away from finite `x` >= 0. */
function ulpStep(x, steps) {
  view.setFloat64(0, x);
  const bits = view.getBigUint64(0) + BigInt(steps);
  if (bits < 0n) return 0;
  view.setBigUint64(0, bits);
  return view.getFloat64(0);
}

/** Marsaglia's xorshift32, from a fixed seed. */
let state = 0x2545f491;
function next32() {
  state ^= state << 13;
  state ^= state >>> 17;
  state ^= state << 5;
  return state >>> 0;
}

const inputs = [];
const seen = new Set();
function add(x) {
  const key = hex(x);
  if (seen.has(key) || inputs.length >= TOTAL) return;
  seen.add(key);
  inputs.push(x);
}

// Special values.
[
  0, -0, Infinity, -Infinity, NaN, 1, 2, 10, 0.1, 0.5, Math.E, Math.SQRT2,
  Math.SQRT1_2, Number.EPSILON, Number.MAX_VALUE, Number.MIN_VALUE,
  2 ** -1022, 2 ** -1022 - 2 ** -1074, 3 * 2 ** -1074,
].forEach(add);

// Negative values: log10 is NaN.
[-1, -0.5, -10, -1e-300, -Number.MIN_VALUE, -Number.MAX_VALUE].forEach(add);
for (let n = 0; n < 44; n++) {
  add(-fromWords(((next32() % 2047) << 20) | (next32() & 0xfffff), next32()));
}

// Powers of ten and their neighbours within two units in the last place.
for (let i = -323; i <= 308; i++) {
  const x = Number(`1e${i}`);
  for (const steps of [0, -1, 1, -2, 2]) add(ulpStep(x, steps));
}

// Neighbours of 1: the |f| < 2**-20 branch of __ieee754_log.
for (let k = 1; k <= 64; k++) {
  add(ulpStep(1, k));
  add(ulpStep(1, -k));
}

// High words at the branch points of __ieee754_log (0x6147a, 0x6b851) and at
// its sqrt(2) normalization point (0x6a09c), for a few exponents.
for (const exponent of [1, 1022, 1023, 1024, 1075, 2046]) {
  for (const word of [0x6147a, 0x6b851, 0x6a09c]) {
    for (const delta of [-1, 0, 1]) {
      add(fromWords((exponent << 20) | (word + delta), next32()));
    }
  }
}

// Every third power of two: f == 0 with k != 0.
for (let k = -1074; k <= 1023; k += 3) add(2 ** k);

// Random subnormals.
for (let n = 0; n < 200; n++) {
  add(fromWords(next32() & 0xfffff, next32()) || Number.MIN_VALUE);
}

// Random positive normal doubles, with the exponent uniform over its range.
while (inputs.length < TOTAL) {
  add(fromWords(((1 + (next32() % 2046)) << 20) | (next32() & 0xfffff), next32()));
}

// Regression inputs, after the 5,909: V8 on arm64 differs from x64 in the last
// bit of Math.log10 for these.
const regression = [
  [0x4005cdde, 0x6b000000], // 2.7255218848586082
  [0x3fd4530d, 0x7f3b5848], // 0.3175691359041406
  [0x3ff6b852, 0xc9aaba7b], // 1.420000827561721
];
for (const [hi, lo] of regression) inputs.push(fromWords(hi, lo));

const lines = inputs.map((x) => `${hex(x)} ${hex(Math.log10(x))}`);

const dart = `// Original code, not ported from Chart.js: V8 Math.log10 reference data.

// Generated by tool/reference/log10_reference.mjs. Do not edit.
// Node.js ${process.version} (${process.platform}-${process.arch}), V8 ${process.versions.v8}:
// fdlibm 5.3 without fused multiply-add. ${lines.length} inputs, the last
// ${regression.length} of them regression inputs.

/// The Node.js version that generated [log10Reference].
const String log10ReferenceNode = '${process.version}';

/// The V8 version that generated [log10Reference].
const String log10ReferenceV8 = '${process.versions.v8}';

/// The architecture of the Node.js build that generated [log10Reference].
const String log10ReferenceArch = '${process.arch}';

/// \`x\` and V8 \`Math.log10(x)\` as IEEE-754 bit patterns in hex, one pair per
/// line.
const String log10Reference = '''
${lines.join('\n')}
''';
`;

writeFileSync(OUT, dart);
console.log(`Wrote ${lines.length} inputs to ${OUT}`);
