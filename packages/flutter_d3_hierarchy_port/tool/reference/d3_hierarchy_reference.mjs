function round2(x) {
  return Math.round(x * 100) / 100;
}

function fmtNum(x) {
  if (Object.is(x, -0)) return "0";
  if (Number.isNaN(x)) return "double.nan";
  if (!Number.isFinite(x)) return x > 0 ? "double.infinity" : "double.negativeInfinity";
  return `${x}`;
}

function escapeDart(s) {
  return s.replaceAll("\\", "\\\\").replaceAll("'", "\\'").replaceAll("$", "\\$");
}

// 1. Parse flare.csv
const flareCsvText = fs.readFileSync(path.join(dataDir, "flare.csv"), "utf8").trim();
const flareLines = flareCsvText.split(/\r?\n/).slice(1);
const flareRows = flareLines.map((line) => {
  const idx = line.indexOf(",");
  const id = line.slice(0, idx);
  const valStr = line.slice(idx + 1).trim();
  const value = valStr === "" ? null : Number(valStr);
  return {id, value};
});

// Check whether JS localeCompare and ASCII code-unit compare agree on flare ties
const flareStrat = d3.stratify().parentId((d) => {
  const i = d.id.lastIndexOf(".");
  return i >= 0 ? d.id.slice(0, i) : null;
});

function cmpAsc(a, b) {
  return a < b ? -1 : a > b ? 1 : 0;
}

const byLocale = flareStrat(flareRows)
  .sum((d) => d.value)
  .sort((a, b) => b.value - a.value || a.data.id.localeCompare(b.data.id));
const byAscii = flareStrat(flareRows)
  .sum((d) => d.value)
  .sort((a, b) => b.value - a.value || cmpAsc(a.data.id, b.data.id));
const localeIds = byLocale.descendants().map((d) => d.data.id);
const asciiIds = byAscii.descendants().map((d) => d.data.id);
let cmpDiffs = 0;
for (let i = 0; i < localeIds.length; i++) {
  if (localeIds[i] !== asciiIds[i]) cmpDiffs++;
}
console.log(`flare localeCompare vs ASCII compareTo order diffs: ${cmpDiffs}`);

