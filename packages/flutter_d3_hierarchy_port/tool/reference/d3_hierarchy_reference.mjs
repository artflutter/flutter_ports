function emitPackNode(node, indent) {
  const sp = " ".repeat(indent);
  const parts = [
    `name: '${escapeDart(node.name)}'`,
    `value: ${fmtNum(node.value)}`,
    `x: ${fmtNum(round2(node.x))}`,
    `y: ${fmtNum(round2(node.y))}`,
    `r: ${fmtNum(round2(node.r))}`,
  ];
  if (node.children) {
    const kids = node.children.map((c) => emitPackNode(c, indent + 2)).join(",\n");
    return `${sp}ExpectedPackNode(${parts.join(", ")}, children: <ExpectedPackNode>[\n${kids},\n${sp}])`;
  }
  return `${sp}ExpectedPackNode(${parts.join(", ")})`;
}

// Serialize expected flare-phi.json / flare-one.json (note D3 3.x reverse on children!)
function emitTreemapNode(node, indent) {
  const sp = " ".repeat(indent);
  const x0 = round2(node.x);
  const y0 = round2(node.y);
  const x1 = round2(node.x + node.dx);
  const y1 = round2(node.y + node.dy);
  const parts = [
    `name: '${escapeDart(node.name)}'`,
    `depth: ${node.depth}`,
    `value: ${fmtNum(node.value)}`,
    `x0: ${fmtNum(x0)}`,
    `y0: ${fmtNum(y0)}`,
    `x1: ${fmtNum(x1)}`,
    `y1: ${fmtNum(y1)}`,
  ];
  if (node.children) {
    const rev = [...node.children].reverse();
    const kids = rev.map((c) => emitTreemapNode(c, indent + 2)).join(",\n");
    return `${sp}ExpectedTreemapNode(${parts.join(", ")}, children: <ExpectedTreemapNode>[\n${kids},\n${sp}])`;
  }
  return `${sp}ExpectedTreemapNode(${parts.join(", ")})`;
}

