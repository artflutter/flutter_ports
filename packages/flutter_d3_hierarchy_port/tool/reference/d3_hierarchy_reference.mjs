// 2. Compute Node.js reference outputs for ALL algorithms on flare.csv
function buildFlare() {
  return flareStrat(flareRows)
    .sum((d) => d.value)
    .sort((a, b) => b.value - a.value || cmpAsc(a.data.id, b.data.id));
}

const refTreeSize = d3.tree().size([960, 500])(buildFlare());
const refTreeNodeSize = d3.tree().nodeSize([20, 40])(buildFlare());
const refClusterSize = d3.cluster().size([960, 500])(buildFlare());
const refClusterNodeSize = d3.cluster().nodeSize([15, 30])(buildFlare());
const refPartition = d3.partition().size([960, 500]).padding(1).round(false)(buildFlare());
const refPartitionRound = d3.partition().size([960, 500]).padding(1).round(true)(buildFlare());
const refTreemapBinary = d3.treemap().tile(d3.treemapBinary).size([960, 500]).paddingInner(2).paddingOuter(4)(buildFlare());
const refTreemapSliceDice = d3.treemap().tile(d3.treemapSliceDice).size([960, 500])(buildFlare());
const refTreemapResquarify = (() => {
  const root = buildFlare();
  const tm = d3.treemap().tile(d3.treemapResquarify).size([960, 500]);
  tm(root);
  // Resize after first pass to test stable resquarify parity!
  tm.size([500, 960])(root);
  return root;
})();
const refPackPad = d3.pack().size([960, 960]).padding(3)(buildFlare());
const refPackCustomR = d3.pack().size([960, 960]).radius((d) => Math.sqrt(d.value) * 0.5).padding(2)(buildFlare());

const sibRadii = [12, 8, 25, 3, 19, 14, 7, 31, 5, 22, 11, 16, 4, 28, 9];
const refSiblings = d3.packSiblings(sibRadii.map((r) => ({r})));
const refEnclose = d3.packEnclose(refSiblings);

function emitXY(root) {
  return root
    .descendants()
    .map((n) => `(${fmtNum(n.x)}, ${fmtNum(n.y)})`)
    .join(",\n  ");
}

function emitRect(root) {
  return root
    .descendants()
    .map((n) => `(${fmtNum(n.x0)}, ${fmtNum(n.y0)}, ${fmtNum(n.x1)}, ${fmtNum(n.y1)})`)
    .join(",\n  ");
}

function emitCirc(root) {
  return root
    .descendants()
    .map((n) => `(${fmtNum(n.x)}, ${fmtNum(n.y)}, ${fmtNum(n.r)})`)
    .join(",\n  ");
}

