import {readdirSync, readFileSync, writeFileSync} from "node:fs";
import path from "node:path";
import {fileURLToPath, pathToFileURL} from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "../../../..");
const d3 = await import(
  pathToFileURL(path.join(repoRoot, "third_party/d3-format/src/index.js")).href
);

function dartString(s) {
  let needsEscape = false;
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    if (c === 0x27 || c === 0x5c || c < 0x20 || c === 0x7f || c === 0x00a0 || c === 0x200f || c === 0x202f) {
      needsEscape = true;
      break;
    }
  }
  if (!needsEscape) {
    return s.includes("$") ? `r'${s}'` : `'${s}'`;
  }
  let out = "'";
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    if (c === 0x27) out += "\\'";
    else if (c === 0x5c) out += "\\\\";
    else if (c === 0x24) out += "\\$";
    else if (c < 0x20 || c === 0x7f || c === 0x00a0 || c === 0x200f || c === 0x202f) {
      out += "\\u" + c.toString(16).padStart(4, "0");
    } else {
      out += s[i];
    }
  }
  return out + "'";
}

