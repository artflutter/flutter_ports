    expect(() => blur(<double>[1, 2, 3], double.nan), throwsRangeError);
    expect(() => blur2(_copy2(), -1), throwsRangeError);
    expect(() => blur2(_copy2(), 1, -1), throwsRangeError);
    expect(
      () => blurImage(BlurImageData(data: Uint8ClampedList(4), width: 1), -0.5),
      throwsRangeError,
