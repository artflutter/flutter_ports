  test(
    'blurImage(data, rx, ry) blurs RGBA channels independently in-place',
    () {
      // 1x14 image with impulse 27 on R, 54 on G, 0 on B, 255 on A at pixel 6.
      final bytes = Uint8ClampedList(14 * 4);
      for (var i = 0; i < 14; ++i) {
        bytes[i * 4 + 3] = 255;
