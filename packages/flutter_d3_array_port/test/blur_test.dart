  test(
    'blurImage(data, rx, ry) supports vertical, 2D, and fractional radii',
    () {
      // 5x5 image with a single white pixel in the center (2, 2).
      final bytes = Uint8ClampedList(5 * 5 * 4);
      const center = (2 * 5 + 2) * 4;
      bytes[center] = 255;
      bytes[center + 3] = 255;

      final imgNoOp = BlurImageData(
        data: Uint8ClampedList.fromList(bytes),
        width: 5,
        height: 5,
      );
      blurImage(imgNoOp, 0, 0);
      expect(imgNoOp.data, bytes);

      final imgVert = BlurImageData(
        data: Uint8ClampedList.fromList(bytes),
        width: 5,
        height: 5,
      );
      blurImage(imgVert, 0, 1);
      // Only column 2 should have non-zero R values.
      for (var y = 0; y < 5; ++y) {
        for (var x = 0; x < 5; ++x) {
          final v = imgVert.data[(y * 5 + x) * 4];
          if (x == 2) {
            expect(v, greaterThan(0));
          } else {
            expect(v, 0);
          }
        }
      }

      final img2d = BlurImageData(
        data: Uint8ClampedList.fromList(bytes),
        width: 5,
        height: 5,
      );
      blurImage(img2d, 0.5);
      // Symmetric around center (2, 2) with peak at center.
      final peak = img2d.data[center];
      expect(peak, greaterThan(0));
      expect(img2d.data[(1 * 5 + 2) * 4], img2d.data[(3 * 5 + 2) * 4]);
      expect(img2d.data[(2 * 5 + 1) * 4], img2d.data[(2 * 5 + 3) * 4]);
      expect(peak, greaterThan(img2d.data[(1 * 5 + 2) * 4]));
    },
  );

