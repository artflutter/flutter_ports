      bytes[6 * 4 + 0] = 27;
      bytes[6 * 4 + 1] = 54;
      final img = BlurImageData(data: bytes, width: 14);
      expect(img.height, 1);

      final out = blurImage(img, 1, 0);
      expect(identical(out, img), isTrue);

      final r = <int>[for (var i = 0; i < 14; ++i) out.data[i * 4 + 0]];
      final g = <int>[for (var i = 0; i < 14; ++i) out.data[i * 4 + 1]];
      final b = <int>[for (var i = 0; i < 14; ++i) out.data[i * 4 + 2]];
