/// viridis.js:3 `ramp(range)`: discrete 256-entry lookup ramp returning a
/// fresh [Rgb] on each call.
///
/// Out-of-range finite and infinite `t` clamp to the first or last entry. A
/// NaN `t` throws an [UnsupportedError], matching `interpolateDiscrete`.
// DIVERGES(d3-scale-chromatic): adapt-chromatic-fast-forms, fixed list clamp.
Rgb Function(double t) _ramp(List<Rgb> range) {
  final table = List<Rgb>.of(range, growable: false);
  final n = table.length;
  final last = n - 1;
  return (t) {
    final int i;
    if (t <= 0) {
      i = 0;
    } else if (t >= 1) {
      i = last;
    } else {
      final idx = (t * n).toInt();
      i = idx < n ? idx : last;
    }
    // DIVERGES(d3-scale-chromatic): adapt-chromatic-color-values, fresh Rgb.
    final c = table[i];
    return Rgb(c.r, c.g, c.b);
  };
}

