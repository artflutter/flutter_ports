/// viridis.js:3 `ramp(range)`: discrete 256-entry lookup ramp returning a
/// shared immutable `const` [Rgb] directly with zero allocation.
///
/// Out-of-range finite and infinite `t` clamp to the first or last entry. A
/// NaN `t` throws an [UnsupportedError], matching `interpolateDiscrete`.
// DIVERGES(d3-scale-chromatic): adapt-chromatic-color-values, const Rgb table.
// DIVERGES(d3-scale-chromatic): adapt-chromatic-fast-forms, zero-alloc lookup.
@pragma('vm:prefer-inline')
@pragma('dart2js:prefer-inline')
@pragma('wasm:prefer-inline')
Rgb _sample(List<Rgb> table, double t) {
  if (t <= 0) return table[0];
  if (t >= 1) return table[255];
  return table[(t * 256).toInt()];
}

/// viridis.js:10 the default export (`interpolateViridis` of index.js:44):
