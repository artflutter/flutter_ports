// Original code, not ported from d3-scale-chromatic: the reference data generator.
//
// Writes test/port/d3_scale_chromatic_reference.dart from upstream
// d3-scale-chromatic v3.1.0 (third_party/d3-scale-chromatic/src/, ESM) on
// Node.js v24.22.1.
//
// Run from packages/flutter_d3_scale_chromatic_port:
//
//   node tool/reference/d3_scale_chromatic_reference.mjs

import {writeFileSync} from "node:fs";
import {registerHooks} from "node:module";
import path from "node:path";
import {fileURLToPath, pathToFileURL} from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "../../../..");
const d3ColorEntry = pathToFileURL(
  path.join(repoRoot, "third_party/d3-color/src/index.js"),
).href;
const d3InterpEntry = pathToFileURL(
  path.join(repoRoot, "third_party/d3-interpolate/src/index.js"),
).href;
const d3ChromEntry = pathToFileURL(
  path.join(repoRoot, "third_party/d3-scale-chromatic/src/index.js"),
).href;

registerHooks({
  resolve(specifier, context, nextResolve) {
    if (specifier === "d3-color") return {url: d3ColorEntry, shortCircuit: true};
    if (specifier === "d3-interpolate") return {url: d3InterpEntry, shortCircuit: true};
    return nextResolve(specifier, context);
  },
});

const d3 = await import(d3ChromEntry);
const d3Color = await import(d3ColorEntry);

const TS = [
  -0.5,
  -0.001,
  0.0,
  1 / 256,
  0.01,
  0.05,
  0.1,
  0.2,
  0.25,
  1 / 3,
  0.4,
  0.5,
  0.6,
  2 / 3,
  0.75,
  0.8,
  0.9,
  0.95,
  0.99,
  255 / 256,
  1.0,
  1.001,
  1.5,
  2.25,
];

const lines = [];
lines.push("// Original code, not ported from d3-scale-chromatic: generated reference data.");
lines.push("// Generated by tool/reference/d3_scale_chromatic_reference.mjs");
lines.push(`// on Node.js ${process.version}.`);
lines.push("");
lines.push("/// Sample `t` values evaluated against upstream d3-scale-chromatic v3.1.0.");
lines.push(`const List<double> referenceTs = [${TS.map((t) => reprNum(t)).join(", ")}];`);
lines.push("");

// Categorical schemes: Map<String, List<String>>
const categoricalNames = Object.keys(d3)
  .filter((k) => k.startsWith("scheme") && typeof d3[k][0] === "string")
  .sort();

lines.push("/// Upstream hex strings for all 11 categorical schemes.");
lines.push("const Map<String, List<String>> referenceCategoricalSchemes = {");
for (const name of categoricalNames) {
  lines.push(`  '${name}': [${d3[name].map((c) => `'${c}'`).join(", ")}],`);
}
lines.push("};");
lines.push("");

// Discrete ColorBrewer schemes: Map<String, List<List<String>?>>
const discreteNames = Object.keys(d3)
  .filter((k) => k.startsWith("scheme") && typeof d3[k][0] !== "string")
  .sort();

lines.push("/// Upstream hex tables for all 27 ColorBrewer discrete schemes.");
lines.push("const Map<String, List<List<String>?>> referenceDiscreteSchemes = {");
for (const name of discreteNames) {
  const arr = d3[name];
  lines.push(`  '${name}': [`);
  for (let i = 0; i < arr.length; i++) {
    if (arr[i] === undefined) {
      lines.push("    null,");
    } else {
      lines.push(`    [${arr[i].map((c) => `'${c}'`).join(", ")}],`);
    }
  }
  lines.push("  ],");
}
lines.push("};");
lines.push("");

// Interpolators: store both upstream string and parsed RGB (r, g, b)
const interpNames = Object.keys(d3)
  .filter((k) => k.startsWith("interpolate"))
  .sort();

lines.push("/// Upstream output strings for all 38 interpolators at [referenceTs].");
lines.push("const Map<String, List<String>> referenceInterpolatorTexts = {");
for (const name of interpNames) {
  const fn = d3[name];
  const vals = TS.map((t) => `'${fn(t)}'`);
  lines.push(`  '${name}': [${vals.join(", ")}],`);
}
lines.push("};");
lines.push("");

lines.push("/// Parsed RGB channels (r, g, b) of upstream outputs at [referenceTs].");
lines.push("const Map<String, List<(double, double, double)>> referenceInterpolatorRgb = {");
for (const name of interpNames) {
  const fn = d3[name];
  const vals = TS.map((t) => {
    const c = d3Color.rgb(fn(t));
    return `(${c.r}.0, ${c.g}.0, ${c.b}.0)`;
  });
  lines.push(`  '${name}': [${vals.join(", ")}],`);
}
lines.push("};");
lines.push("");

function reprNum(n) {
  if (Object.is(n, -0)) return "-0.0";
  const s = String(n);
  return s.includes(".") || s.includes("e") ? s : `${s}.0`;
}

const outPath = path.join(here, "../../test/port/d3_scale_chromatic_reference.dart");
writeFileSync(outPath, `${lines.join("\n")}\n`);
console.log(
  `Wrote ${outPath}: ${categoricalNames.length} categorical, ` +
    `${discreteNames.length} discrete, ${interpNames.length} interpolators x ${TS.length} t values.`,
);
