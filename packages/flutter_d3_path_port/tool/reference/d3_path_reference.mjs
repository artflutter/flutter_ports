import {writeFileSync} from "node:fs";
import path from "node:path";
import {fileURLToPath, pathToFileURL} from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "../../../..");
const d3PathEntry = pathToFileURL(
  path.join(repoRoot, "third_party/d3-path/src/index.js"),
).href;

const {path: d3Path, pathRound} = await import(d3PathEntry);

function runScript(makePath) {
  const results = {};

  // 1. Negative-zero, integers, fractions, negative halves.
  {
    const p = makePath();
    p.moveTo(-0, 0);
    p.lineTo(-0.5, -1.5);
    p.lineTo(0.5, 1.5);
    p.lineTo(-0.0005, -0.0015);
    p.lineTo(123.456789, -987.654321);
    p.closePath();
    results.roundingAndNegatives = `${p}`;
  }

  // 2. Polyline + curves + rect.
  {
    const p = makePath();
    p.moveTo(10.25, -20.75);
    p.lineTo(100.125, 50.5);
    p.quadraticCurveTo(150.3333, 25.6666, 200.9999, 80.0001);
    p.bezierCurveTo(210.5, 120.5, 180.25, 190.75, 120.0, 200.0);
    p.rect(5.5, 15.25, 40.75, 30.125);
    p.closePath();
    results.curvesAndRect = `${p}`;
  }

  // 3. Arcs (CW, CCW, full circles, negative sweep, empty start, zero radius).
  {
    const p = makePath();
    p.arc(100, 100, 50, 0, Math.PI / 2, false);
    p.arc(100, 100, 50, Math.PI / 2, Math.PI * 1.75, false);
    p.arc(200, 100, 30, 0, -Math.PI * 1.5, true);
    p.arc(300, 100, 25, 0.3, 0.3 + 2 * Math.PI, false);
    p.arc(400, 100, 25, 0.3, 0.3 - 2 * Math.PI, true);
    p.arc(500, 100, 0, 0, Math.PI, false);
    p.closePath();
    results.arcs = `${p}`;
  }

  // 4. arcTo (empty, coincident, collinear, zero radius, CW & CCW corners).
  {
    const p = makePath();
    p.arcTo(10, 20, 30, 40, 5);
    p.arcTo(10, 20, 50, 60, 5);
    p.arcTo(20, 30, 30, 40, 5);
    p.arcTo(100, 30, 100, 120, 0);
    p.arcTo(270, 39, 163, 100, 53);
    p.arcTo(270, 39, 363, 100, 53);
    p.arcTo(100, 100, 200, 200, 25);
    results.arcTo = `${p}`;
  }

  // 5. Edge values: sub-epsilon, huge coordinates, closePath without moveTo.
  {
    const p = makePath();
    p.lineTo(1e-7, 1e-6);
    p.lineTo(1000000, -1000000);
    p.closePath();
    p.closePath(); // ignored after closePath cleared _x1 when _x0 was null
    p.moveTo(0, 0);
    p.arc(0, 0, 10, 0, 1e-16, false);
    p.arc(0, 0, 10, 0, 1e-16, true);
    results.edges = `${p}`;
  }

  return results;
}

const full = runScript(() => d3Path());
const round0 = runScript(() => pathRound(0));
const round1 = runScript(() => pathRound(1));
const round3 = runScript(() => pathRound(3));
const round6 = runScript(() => pathRound(6));
const round16 = runScript(() => pathRound(16));

// Number formatting stress cases for pathRound(d) across d = 0..6 and full.
const sampleNumbers = [
  0, -0, 1, -1, 0.5, -0.5, 1.5, -1.5, 2.5, -2.5,
  0.05, -0.05, 0.15, -0.15, 0.25, -0.25, 0.005, -0.005,
  0.0005, -0.0005, 0.0015, -0.0015, 0.1 + 0.2, -(0.1 + 0.2),
  Math.PI, -Math.PI, Math.E, -Math.E,
  1e-7, -1e-7, 1e-6, -1e-6, 1e-5, -1e-5,
  999.9999, -999.9999, 123456.789012, -123456.789012,
  1e12, -1e12, 1e15, -1e15,
];

function formatNumberBatch(digits) {
  const p = digits === null ? d3Path() : pathRound(digits);
  for (let i = 0; i < sampleNumbers.length; i += 2) {
    p.moveTo(sampleNumbers[i], sampleNumbers[i + 1]);
  }
  return `${p}`;
}

