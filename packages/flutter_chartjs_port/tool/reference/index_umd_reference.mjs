// Original code, not ported from Chart.js: the generator of index_umd_reference.dart.
//
// It writes test/port/index_umd_reference.dart, the data of
// test/port/index.umd_test.dart (Chart.js ADR 0048, section 1): the keys
// that the UMD entry src/index.umd.ts gives the class value `Chart` of a
// build of the pinned Chart.js. See the header of
// tool/reference/scale_chart_common.mjs for the method, the build and the
// checks of loadChartJs.
//
// The generator evaluates dist/chart.umd.js, the UMD bundle next to
// dist/chart.js of the build, as a CommonJS module: the `package.json` of
// the build has `"type": "module"`, so `require` would load the file as an
// ES module without exports. The bundle body runs src/index.umd.ts:28-51.
// Then the generator records, in order:
//
// - `Object.keys(Chart)`: the enumerable own keys of the class. The static
//   methods `register` and `unregister` are not enumerable, so they are not
//   in the list.
// - `Object.keys(Chart.helpers)`: the runtime exports of
//   src/helpers/index.ts in code unit order, as the module namespace gives
//   them to the spread of :30.
// - `Object.keys(Chart.platforms)`: the exports of src/platform/index.js in
//   code unit order (:20).
//
// Usage, from packages/flutter_chartjs_port, with the darwin-arm64 build of
// Node.js v24.22.1 (Chart.js ADR 0045) and with the Dart SDK on the PATH
// (the generator formats its output with `dart format`):
//
//   CHARTJS_DIST=<build>/dist/chart.js \
//     node tool/reference/index_umd_reference.mjs
//
// The path can also be the first argument. The generator stops unless the
// build is at the `commit` of the Chart.js entry of tool/port_sources.yaml
// (loadChartJs).

import {execFileSync} from 'node:child_process';
import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath, pathToFileURL} from 'node:url';

import {loadChartJs} from './scale_chart_common.mjs';

const OUT = fileURLToPath(
  new URL('../../test/port/index_umd_reference.dart', import.meta.url),
);
const PORT_SOURCES = new URL('../port_sources.yaml', import.meta.url);

/** Writes [message] to stderr and stops the process. */
function stop(message) {
  console.error(message);
  process.exit(1);
}

/**
 * The version and the commit of the Chart.js entry of
 * tool/port_sources.yaml. A copy of readPin in scale_chart_common.mjs,
 * without the release part.
 */
function readPin() {
  const path = fileURLToPath(PORT_SOURCES);
  const entry = readFileSync(path, 'utf8')
    .split(/^ {2}- header: /m)
    .find((e) => e.startsWith('Chart.js\n'));
  const version = entry?.match(/^ {4}version: "?v([^"\s]+)"?\s*$/m)?.[1];
  const commit = entry?.match(/^ {6}commit: "?([0-9a-f]{40})"?\s*$/m)?.[1];
  if (!version || !commit) stop(`${path} has no version and commit for Chart.js.`);
  return {version, commit};
}

// loadChartJs stops unless the build is at the pinned commit.
await loadChartJs();
const PIN = readPin();

const dist = process.argv[2] ?? process.env.CHARTJS_DIST;
const umd = fileURLToPath(new URL('chart.umd.js', pathToFileURL(dist)));
if (!existsSync(umd)) stop(`${umd} is missing: the build has no UMD bundle.`);

/** The UMD bundle as a CommonJS module: its `module.exports`. */
function loadUmd(path) {
  const module = {exports: {}};
  new Function('module', 'exports', readFileSync(path, 'utf8'))(module, module.exports);
  return module.exports;
}

const Chart = loadUmd(umd);
if (typeof Chart !== 'function' || Chart.Chart !== Chart) {
  stop(`${umd} does not give the class Chart.`);
}

/** A Dart string literal in single quotes of [s]. */
function dartString(s) {
  return `'${s.replace(/[\\'$]/g, (c) => `\\${c}`)}'`;
}

/** A Dart list literal of the strings [keys], one on each line. */
function dartList(keys) {
  return `[\n${keys.map((k) => `  ${dartString(k)},\n`).join('')}]`;
}

const chartKeys = Object.keys(Chart);
const helpersKeys = Object.keys(Chart.helpers);
const platformsKeys = Object.keys(Chart.platforms);

const generator = 'tool/reference/index_umd_reference.mjs';
const out = `// Original code, not ported from Chart.js: index.umd reference data.

// Generated by ${generator}. Do not edit.
// Node.js ${process.version} (${process.platform}-${process.arch}), V8 ${process.versions.v8}:
// dist/chart.umd.js of a build of Chart.js v${PIN.version} at the commit
// ${PIN.commit}. ${chartKeys.length} keys of Chart, ${helpersKeys.length} of
// Chart.helpers, ${platformsKeys.length} of Chart.platforms.

/// The Node.js version that generated the data.
const String indexUmdReferenceNode = '${process.version}';

/// The V8 version that generated the data.
const String indexUmdReferenceV8 = '${process.versions.v8}';

/// The architecture of the Node.js build that generated the data.
const String indexUmdReferenceArch = '${process.arch}';

/// The Chart.js version of the build that generated the data: the pin
/// version of tool/port_sources.yaml, without its "v".
const String indexUmdReferenceDist = '${PIN.version}';

/// The Chart.js commit of the build that generated the data.
const String indexUmdReferenceCommit = '${PIN.commit}';

/// \`Object.keys(Chart)\` after the body of src/index.umd.ts, in order.
const List<String> indexUmdReferenceChartKeys = ${dartList(chartKeys)};

/// \`Object.keys(Chart.helpers)\`, in order.
const List<String> indexUmdReferenceHelpersKeys = ${dartList(helpersKeys)};

/// \`Object.keys(Chart.platforms)\`, in order.
const List<String> indexUmdReferencePlatformsKeys = ${dartList(platformsKeys)};
`;
writeFileSync(OUT, out);
execFileSync('dart', ['format', OUT], {stdio: 'inherit'});
console.log(
  `Wrote ${chartKeys.length}, ${helpersKeys.length} and ${platformsKeys.length} keys to ${OUT}`,
);
