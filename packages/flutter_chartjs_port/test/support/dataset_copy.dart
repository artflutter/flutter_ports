// Original code, not ported from Chart.js: a copy of a built-in dataset.

/// `copyWith` of the parameters of [Dataset] on a dataset of a built-in
/// class (Chart.js ADR 0189).
///
/// `Dataset` has no `copyWith`: a dataset class of another package takes
/// only the parameters of its chart type. The tests that apply one base
/// parameter to each of the 8 built-in classes call this extension.
library;

import 'package:flutter/foundation.dart' show Key;
import 'package:flutter_chartjs_port/flutter_chartjs_port.dart';

/// The copy of a built-in dataset through the type [Dataset].
extension BuiltInDatasetCopy on Dataset {
  /// The `copyWith` of the class of this dataset, with the parameters of
  /// [Dataset].
  Dataset copyWith({
    Key? key,
    String? label,
    bool? hidden,
    int? order,
    ChartClip? clip,
    ChartValue<ChartPaint>? backgroundColor,
    ChartValue<ChartPaint>? borderColor,
    double? borderWidth,
    ChartValue<ChartPaint>? hoverBackgroundColor,
    ChartValue<ChartPaint>? hoverBorderColor,
    double? hoverBorderWidth,
    ChartShadow? shadow,
    TooltipCallbacks? tooltipCallbacks,
    Map<String, Object?>? extra,
  }) => switch (this) {
    final BarDataset d => d.copyWith(
      key: key,
      label: label,
      hidden: hidden,
      order: order,
      clip: clip,
      backgroundColor: backgroundColor,
      borderColor: borderColor,
      borderWidth: borderWidth,
      hoverBackgroundColor: hoverBackgroundColor,
      hoverBorderColor: hoverBorderColor,
      hoverBorderWidth: hoverBorderWidth,
      shadow: shadow,
      tooltipCallbacks: tooltipCallbacks,
      extra: extra,
    ),
    final LineDataset d => d.copyWith(
      key: key,
      label: label,
      hidden: hidden,
      order: order,
      clip: clip,
      backgroundColor: backgroundColor,
      borderColor: borderColor,
      borderWidth: borderWidth,
      hoverBackgroundColor: hoverBackgroundColor,
      hoverBorderColor: hoverBorderColor,
      hoverBorderWidth: hoverBorderWidth,
      shadow: shadow,
      tooltipCallbacks: tooltipCallbacks,
      extra: extra,
    ),
    final ScatterDataset d => d.copyWith(
      key: key,
      label: label,
      hidden: hidden,
      order: order,
      clip: clip,
      backgroundColor: backgroundColor,
      borderColor: borderColor,
      borderWidth: borderWidth,
      hoverBackgroundColor: hoverBackgroundColor,
      hoverBorderColor: hoverBorderColor,
      hoverBorderWidth: hoverBorderWidth,
      shadow: shadow,
      tooltipCallbacks: tooltipCallbacks,
      extra: extra,
    ),
    final BubbleDataset d => d.copyWith(
      key: key,
      label: label,
      hidden: hidden,
      order: order,
      clip: clip,
      backgroundColor: backgroundColor,
      borderColor: borderColor,
      borderWidth: borderWidth,
      hoverBackgroundColor: hoverBackgroundColor,
      hoverBorderColor: hoverBorderColor,
      hoverBorderWidth: hoverBorderWidth,
      shadow: shadow,
      tooltipCallbacks: tooltipCallbacks,
      extra: extra,
    ),
    final PieDataset d => d.copyWith(
      key: key,
      label: label,
      hidden: hidden,
      order: order,
      clip: clip,
      backgroundColor: backgroundColor,
      borderColor: borderColor,
      borderWidth: borderWidth,
      hoverBackgroundColor: hoverBackgroundColor,
      hoverBorderColor: hoverBorderColor,
      hoverBorderWidth: hoverBorderWidth,
      shadow: shadow,
      tooltipCallbacks: tooltipCallbacks,
      extra: extra,
    ),
    final DoughnutDataset d => d.copyWith(
      key: key,
      label: label,
      hidden: hidden,
      order: order,
      clip: clip,
      backgroundColor: backgroundColor,
      borderColor: borderColor,
      borderWidth: borderWidth,
      hoverBackgroundColor: hoverBackgroundColor,
      hoverBorderColor: hoverBorderColor,
      hoverBorderWidth: hoverBorderWidth,
      shadow: shadow,
      tooltipCallbacks: tooltipCallbacks,
      extra: extra,
    ),
    final PolarAreaDataset d => d.copyWith(
      key: key,
      label: label,
      hidden: hidden,
      order: order,
      clip: clip,
      backgroundColor: backgroundColor,
      borderColor: borderColor,
      borderWidth: borderWidth,
      hoverBackgroundColor: hoverBackgroundColor,
      hoverBorderColor: hoverBorderColor,
      hoverBorderWidth: hoverBorderWidth,
      shadow: shadow,
      tooltipCallbacks: tooltipCallbacks,
      extra: extra,
    ),
    final RadarDataset d => d.copyWith(
      key: key,
      label: label,
      hidden: hidden,
      order: order,
      clip: clip,
      backgroundColor: backgroundColor,
      borderColor: borderColor,
      borderWidth: borderWidth,
      hoverBackgroundColor: hoverBackgroundColor,
      hoverBorderColor: hoverBorderColor,
      hoverBorderWidth: hoverBorderWidth,
      shadow: shadow,
      tooltipCallbacks: tooltipCallbacks,
      extra: extra,
    ),
    _ => throw UnsupportedError('No built-in dataset: $runtimeType.'),
  };
}
