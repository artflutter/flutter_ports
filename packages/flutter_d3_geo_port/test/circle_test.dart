    final o = (geoCircle()..center = const (0, 90))();
    expect(o.type, 'Polygon');
    final expected = <GeoPosition>[
      for (final x in range(360, -1, -2)) (x >= 180 ? x - 360 : x, 0),
    ];
    assertRingInDelta(o.coordinates[0], expected);
  });

  test('circle.center([45, 45])', () {
    final o = (geoCircle()
      ..center = const (45, 45)
      ..radius = 0)();
    expect(o.type, 'Polygon');
    assertPositionInDelta(o.coordinates[0][0], const (45, 45));
  });

