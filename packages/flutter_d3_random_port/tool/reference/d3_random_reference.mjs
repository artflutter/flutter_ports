function fmtNum(v) {
  if (Number.isNaN(v)) return "double.nan";
  if (v === Infinity) return "double.infinity";
  if (v === -Infinity) return "double.negativeInfinity";
  return Object.is(v, -0) ? "-0.0" : Number(v).toString();
}

const lcgSeeds = [
  0,
  0.42,
  0.44871573888282423,
  0.999999999,
  1,
  42,
  -42,
  0x7fffffff,
  0xffffffff,
  1234567890123,
];

const lcgVectors = lcgSeeds.map((seed) => {
  const g = d3.randomLcg(seed);
  const draws = [];
  for (let i = 0; i < 32; ++i) draws.push(g());
  return [seed, draws];
});

