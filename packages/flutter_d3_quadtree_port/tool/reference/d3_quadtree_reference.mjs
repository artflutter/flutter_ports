// Original code, not ported from d3-quadtree: Node.js reference vector generator.
//
// Run from repo root:
//   node packages/flutter_d3_quadtree_port/tool/reference/d3_quadtree_reference.mjs

import fs from "node:fs";
import path from "node:path";
import {fileURLToPath, pathToFileURL} from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = path.resolve(here, "../..");
const repo = path.resolve(pkg, "../..");
const {quadtree} = await import(
  pathToFileURL(path.join(repo, "third_party/d3-quadtree/src/index.js")).href
);

class Lcg {
  constructor(seed) {
    this.seed = seed;
  }
  nextDouble() {
    this.seed = (this.seed * 48271) % 2147483647;
    return this.seed / 2147483647.0;
  }
}

const rng = new Lcg(2026);
const points = [];
for (let i = 0; i < 200; ++i) {
  const x = Math.round((rng.nextDouble() * 1000 - 250) * 100) / 100;
  const y = Math.round((rng.nextDouble() * 1000 - 250) * 100) / 100;
  points.push([x, y]);
}
// Inject some coincident points and boundary points.
points.push(points[7].slice(), points[7].slice(), points[42].slice(), [-250, -250], [750, 750]);

const tree = quadtree(points);
const ext = tree.extent();
const dataOut = tree.data();
const sizeOut = tree.size();

// Pre-order and post-order traversal bounds.
const preBounds = [];
tree.visit((node, x0, y0, x1, y1) => {
  preBounds.push([x0, y0, x1, y1, node.length ? 1 : 0]);
});
const postBounds = [];
tree.visitAfter((node, x0, y0, x1, y1) => {
  postBounds.push([x0, y0, x1, y1, node.length ? 1 : 0]);
});

// Pruned rectangular range query using visit.
const rx0 = -50, ry0 = 20, rx1 = 380, ry1 = 440;
const rangeVisited = [];
const rangeHits = [];
tree.visit((node, x0, y0, x1, y1) => {
  rangeVisited.push([x0, y0, x1, y1]);
  if (!node.length) {
    let leaf = node;
    do {
      const d = leaf.data;
      if (d[0] >= rx0 && d[0] < rx1 && d[1] >= ry0 && d[1] < ry1) {
        rangeHits.push(d);
      }
    } while ((leaf = leaf.next));
  }
  return x0 >= rx1 || y0 >= ry1 || x1 < rx0 || y1 < ry0;
});

// Nearest-neighbor queries (unbounded and bounded radius).
const queries = [];
const findUnbounded = [];
const findBounded = [];
for (let i = 0; i < 40; ++i) {
  const qx = Math.round((rng.nextDouble() * 1100 - 300) * 100) / 100;
  const qy = Math.round((rng.nextDouble() * 1100 - 300) * 100) / 100;
  const r = Math.round((20 + rng.nextDouble() * 120) * 100) / 100;
  queries.push([qx, qy, r]);
  findUnbounded.push(tree.find(qx, qy) ?? null);
  findBounded.push(tree.find(qx, qy, r) ?? null);
}

// Copy, remove every 3rd point, re-check size, data, and find.
const copyTree = tree.copy();
for (let i = 0; i < points.length; i += 3) {
  copyTree.remove(points[i]);
}
const afterRemoveSize = copyTree.size();
const afterRemoveData = copyTree.data();
const afterRemoveFind = queries.slice(0, 15).map(([qx, qy]) => copyTree.find(qx, qy) ?? null);

// Incremental cover + add sequence.
const incTree = quadtree();
const incExtents = [];
for (const p of [
  [10.25, -5.75],
  [25.5, 40.0],
  [-100.0, 12.0],
  [500.0, -300.0],
  [10.25, -5.75],
]) {
  incTree.add(p);
  incExtents.push(incTree.extent());
}

const fmtNum = (n) => (Object.is(n, -0) ? "-0.0" : Number.isInteger(n) ? `${n}.0` : String(n));
const fmtPt = (p) => (p == null ? "null" : `(${fmtNum(p[0])}, ${fmtNum(p[1])})`);
const fmtExt = (e) => `((${fmtNum(e[0][0])}, ${fmtNum(e[0][1])}), (${fmtNum(e[1][0])}, ${fmtNum(e[1][1])}))`;
const fmtBound = (b) => `(${fmtNum(b[0])}, ${fmtNum(b[1])}, ${fmtNum(b[2])}, ${fmtNum(b[3])}, ${b[4] === 1})`;
const fmtRect = (b) => `(${fmtNum(b[0])}, ${fmtNum(b[1])}, ${fmtNum(b[2])}, ${fmtNum(b[3])})`;

const lines = [
  "// Original code, not ported from d3-quadtree: Node.js reference vectors.",
  "// Generated by tool/reference/d3_quadtree_reference.mjs for v3.0.1.",
  "",
  "/// Input points for Node.js reference parity tests.",
  `const List<(double, double)> refPoints = <(double, double)>[`,
  ...points.map((p) => `  ${fmtPt(p)},`),
  "];",
  "",
  "/// Expected extent after `quadtree(refPoints)`.",
  `const ((double, double), (double, double)) refExtent =`,
  `    ${fmtExt(ext)};`,
  "",
  "/// Expected `size()`.",
  `const int refSize = ${sizeOut};`,
  "",
  "/// Expected `data()` order.",
  `const List<(double, double)> refData = <(double, double)>[`,
  ...dataOut.map((p) => `  ${fmtPt(p)},`),
  "];",
  "",
  "/// Expected pre-order `visit` bounds `(x0, y0, x1, y1, isInternal)`.",
  `const List<(double, double, double, double, bool)> refPreVisit = [`,
  ...preBounds.map((b) => `  ${fmtBound(b)},`),
  "];",
  "",
  "/// Expected post-order `visitAfter` bounds `(x0, y0, x1, y1, isInternal)`.",
  `const List<(double, double, double, double, bool)> refPostVisit = [`,
  ...postBounds.map((b) => `  ${fmtBound(b)},`),
  "];",
  "",
  "/// Range query rectangle `(rx0, ry0, rx1, ry1)`.",
  `const (double, double, double, double) refRangeBox =`,
  `    (${fmtNum(rx0)}, ${fmtNum(ry0)}, ${fmtNum(rx1)}, ${fmtNum(ry1)});`,
  "",
  "/// Expected quads visited during pruned range query.",
  `const List<(double, double, double, double)> refRangeVisited = [`,
  ...rangeVisited.map((b) => `  ${fmtRect(b)},`),
  "];",
  "",
  "/// Expected points found in pruned range query.",
  `const List<(double, double)> refRangeHits = <(double, double)>[`,
  ...rangeHits.map((p) => `  ${fmtPt(p)},`),
  "];",
  "",
  "/// Nearest-neighbor query coordinates `(x, y, radius)`.",
  `const List<(double, double, double)> refQueries = [`,
  ...queries.map((q) => `  (${fmtNum(q[0])}, ${fmtNum(q[1])}, ${fmtNum(q[2])}),`),
  "];",
  "",
  "/// Expected `find(x, y)` results.",
  `const List<(double, double)?> refFindUnbounded = <(double, double)?>[`,
  ...findUnbounded.map((p) => `  ${fmtPt(p)},`),
  "];",
  "",
  "/// Expected `find(x, y, radius)` results.",
  `const List<(double, double)?> refFindBounded = <(double, double)?>[`,
  ...findBounded.map((p) => `  ${fmtPt(p)},`),
  "];",
  "",
  "/// Expected size after removing every 3rd point from a copy.",
  `const int refAfterRemoveSize = ${afterRemoveSize};`,
  "",
  "/// Expected `data()` after removing every 3rd point from a copy.",
  `const List<(double, double)> refAfterRemoveData = <(double, double)>[`,
  ...afterRemoveData.map((p) => `  ${fmtPt(p)},`),
  "];",
  "",
  "/// Expected `find(x, y)` on the first 15 queries after removal.",
  `const List<(double, double)?> refAfterRemoveFind = <(double, double)?>[`,
  ...afterRemoveFind.map((p) => `  ${fmtPt(p)},`),
  "];",
  "",
  "/// Expected extents during incremental `add` sequence.",
  `const List<((double, double), (double, double))> refIncExtents = [`,
  ...incExtents.map((e) => `  ${fmtExt(e)},`),
  "];",
  "",
];

const outPath = path.join(pkg, "test/port/d3_quadtree_reference.dart");
fs.writeFileSync(outPath, lines.join("\n"));
console.log(`Wrote ${outPath} (${points.length} pts, ${preBounds.length} nodes, ${queries.length} queries)`);
